/* INITIALISE DATABASE SCHEMA */
CREATE OR REPLACE FUNCTION public.create_schema()
    RETURNS VOID
    SET search_path = ''
AS $$
BEGIN
    CREATE SCHEMA IF NOT EXISTS watchdog;

    GRANT USAGE ON SCHEMA watchdog TO anon, authenticated, service_role;
    GRANT ALL ON ALL TABLES IN SCHEMA watchdog TO anon, authenticated, service_role;
    GRANT ALL ON ALL ROUTINES IN SCHEMA watchdog TO anon, authenticated, service_role;
    GRANT ALL ON ALL SEQUENCES IN SCHEMA watchdog TO anon, authenticated, service_role;

    ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA watchdog
        GRANT ALL ON TABLES TO anon, authenticated, service_role;
    ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA watchdog
        GRANT ALL ON ROUTINES TO anon, authenticated, service_role;
    ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA watchdog
        GRANT ALL ON SEQUENCES TO anon, authenticated, service_role;
END;
$$ LANGUAGE plpgsql;


/* INITIALISE DATABASE TABLES */
CREATE OR REPLACE FUNCTION watchdog.create_tables()
    RETURNS VOID
    SET search_path = 'watchdog'
AS $$
BEGIN
    CREATE TABLE IF NOT EXISTS watchdog.items (
        sku VARCHAR(20) NOT NULL,
        department_en TEXT,
        department_zh TEXT,
        category_en TEXT,
        category_zh TEXT,
        subcategory_en TEXT,
        subcategory_zh TEXT,
        brand_en TEXT,
        brand_zh TEXT,
        name_en TEXT,
        name_zh TEXT,
        created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
        CONSTRAINT items_pkey PRIMARY KEY (sku)
    );

    CREATE TABLE IF NOT EXISTS watchdog.supermarkets (
        supermarket VARCHAR(10) NOT NULL,
        preference INT GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL,
        created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
        CONSTRAINT supermarkets_pkey PRIMARY KEY (supermarket)
    );

    CREATE TABLE IF NOT EXISTS watchdog.users (
        user_id TEXT NOT NULL,
        display_language VARCHAR DEFAULT 'en',
        is_subscribed BOOLEAN DEFAULT FALSE,
        created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
        CONSTRAINT users_pkey PRIMARY KEY (user_id)
    );

    CREATE TABLE IF NOT EXISTS watchdog.prices (
        sku VARCHAR(20) NOT NULL,
        effective_date DATE NOT NULL,
        supermarket VARCHAR(10) NOT NULL,
        promotion_en TEXT,
        promotion_zh TEXT,
        original_price NUMERIC(6, 2) NOT NULL,
        unit_price NUMERIC(6, 2) NOT NULL,
        created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
        CONSTRAINT prices_pkey PRIMARY KEY (sku, effective_date, supermarket),
        CONSTRAINT fk_prices_items_sku FOREIGN KEY (sku)
            REFERENCES items(sku) ON DELETE CASCADE,
        CONSTRAINT fk_prices_supermarkets_supermarket FOREIGN KEY (supermarket)
            REFERENCES supermarkets(supermarket)
    );

    CREATE TABLE IF NOT EXISTS watchdog.deals (
        sku VARCHAR(20) NOT NULL,
        supermarket VARCHAR(10) NOT NULL,
        promotion_en TEXT,
        promotion_zh TEXT,
        original_price NUMERIC(6, 2),
        unit_price NUMERIC(6, 2),
        frequency INT,
        average_price NUMERIC(6, 2),
        std_price NUMERIC(6, 2),
        q0_price NUMERIC(6, 2),
        bid_price NUMERIC(6, 2),
        q4_price NUMERIC(6, 2),
        is_deal BOOLEAN DEFAULT FALSE,
        created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
        CONSTRAINT deals_pkey PRIMARY KEY (sku),
        CONSTRAINT fk_deals_items_sku FOREIGN KEY (sku)
            REFERENCES items(sku) ON DELETE CASCADE,
        CONSTRAINT fk_deals_supermarkets_supermarket FOREIGN KEY (supermarket)
            REFERENCES supermarkets(supermarket)
    );

    CREATE TABLE IF NOT EXISTS watchdog.watchlists (
        user_id TEXT NOT NULL,
        sku VARCHAR(20) NOT NULL,
        created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
        CONSTRAINT watchlists_pkey PRIMARY KEY (user_id, sku),
        CONSTRAINT fk_watchlists_users_user_id FOREIGN KEY (user_id)
            REFERENCES users(user_id) ON DELETE CASCADE,
        CONSTRAINT fk_watchlists_items_sku FOREIGN KEY (sku)
            REFERENCES items(sku) ON DELETE CASCADE
    );

    CREATE TABLE IF NOT EXISTS watchdog.omissions (
        omission_date DATE NOT NULL,
        created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
        CONSTRAINT omissions_pkey PRIMARY KEY (omission_date)
    );

    CREATE INDEX IF NOT EXISTS idx_prices_sku_date ON prices(sku, effective_date);
    CREATE INDEX IF NOT EXISTS idx_prices_date ON prices(effective_date);
    CREATE INDEX IF NOT EXISTS idx_prices_sku ON prices(sku);
    CREATE INDEX IF NOT EXISTS idx_deals_is_deal ON deals(is_deal) WHERE is_deal = TRUE;
    CREATE INDEX IF NOT EXISTS idx_deals_sku ON deals(sku);
    CREATE INDEX IF NOT EXISTS idx_watchlists_user_id ON watchlists(user_id);
    CREATE INDEX IF NOT EXISTS idx_watchlists_sku ON watchlists(sku);
    CREATE INDEX IF NOT EXISTS idx_users_is_subscribed ON users(is_subscribed) WHERE is_subscribed = TRUE;

    ALTER TABLE items ENABLE ROW LEVEL SECURITY;
    ALTER TABLE prices ENABLE ROW LEVEL SECURITY;
    ALTER TABLE supermarkets ENABLE ROW LEVEL SECURITY;
    ALTER TABLE users ENABLE ROW LEVEL SECURITY;
    ALTER TABLE deals ENABLE ROW LEVEL SECURITY;
    ALTER TABLE watchlists ENABLE ROW LEVEL SECURITY;
    ALTER TABLE omissions ENABLE ROW LEVEL SECURITY;
END;
$$ LANGUAGE plpgsql;
